"""Общие мелкие утилиты, чтобы не дублировать их по модулям (DRY)."""


def distance_to_cosine(dist):
    """L2-расстояние между L2-нормированными векторами → косинусное сходство.

    Векторы в инксе нормированы (L2=1), поэтому
    cosine = 1 - dist²/2, где dist — L2-расстояние. Ограничиваем в [0, 1]:
    dist=None (запись без вектора) → 0, dist=0 → 1, dist≥√2 → 0.
    """
    if dist is None:
        return 0.0
    return max(0.0, min(1.0, 1.0 - (float(dist) ** 2) / 2.0))
